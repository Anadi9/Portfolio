// Question-shaped headings in the notes, as FAQPage data for answer engines.
// Only what the post already says: an `## …?` heading and the paragraph under
// it (plus the list that follows when that paragraph ends with a colon), as
// plain text. A post needs two or more to count as Q&A-shaped.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { collect, root, streamPath } from './content.mjs';

const MAX_ANSWER = 600;

const plain = (s) =>
  s
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/(\*\*|__|\*|_|`)/g, '')
    .replace(/\s+/g, ' ')
    .trim();

export function extractFaq(source) {
  const lines = source.replace(/^---\n[\s\S]*?\n---\n/, '').split('\n');
  const out = [];
  let fence = false;
  for (let i = 0; i < lines.length; i++) {
    if (/^\s*(```|~~~)/.test(lines[i])) fence = !fence;
    if (fence) continue;
    const h = /^##\s+(.+\?)\s*$/.exec(lines[i]);
    if (!h) continue;
    let j = i + 1;
    while (j < lines.length && !lines[j].trim()) j++;
    const para = [];
    while (j < lines.length && lines[j].trim() && !/^(#|```|<|\||- |\* |\d+\. )/.test(lines[j])) para.push(lines[j++]);
    let answer = plain(para.join(' '));
    if (answer.endsWith(':')) {
      while (j < lines.length && !lines[j].trim()) j++;
      const items = [];
      while (j < lines.length && /^(- |\* |\d+\. )/.test(lines[j])) {
        let item = lines[j++].replace(/^(- |\* |\d+\. )/, '');
        // A list item can wrap onto indented lines.
        while (j < lines.length && /^\s{2,}\S/.test(lines[j])) item += ` ${lines[j++].trim()}`;
        items.push(plain(item));
      }
      // "…with a phased start:" followed by a table, not a list: no complete answer to quote.
      if (!items.length) continue;
      answer = `${answer} ${items.join(' ')}`;
    }
    if (answer) out.push({ q: plain(h[1]).replace(/^\d+\.\s+/, ''), a: answer.length > MAX_ANSWER ? `${answer.slice(0, MAX_ANSWER - 1).trimEnd()}…` : answer });
  }
  return out.length >= 2 ? out : [];
}

/** The generated module's text, so the test can check it is current. */
export function faqModule() {
  const faq = {};
  for (const p of collect().sort((a, b) => `${a.dir}/${a.slug}`.localeCompare(`${b.dir}/${b.slug}`))) {
    const items = extractFaq(readFileSync(join(root, 'src', 'content', p.dir, `${p.slug}.mdx`), 'utf8'));
    if (items.length) faq[`/${streamPath[p.stream]}/${p.slug}`] = items;
  }
  return `/* Generated by scripts/generate-faq.mjs from the notes' question headings. Do not edit. */\nexport const FAQ: Record<string, { q: string; a: string }[]> = ${JSON.stringify(faq, null, 2)};\n`;
}
