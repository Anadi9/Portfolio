// The header's Resources menu: each blog stream's post count, its index path
// and its three newest posts. Built from frontmatter at predev/prebuild so the
// header (on every page) never imports the MDX itself.
import { collect, pathOf, streamPath } from './content.mjs';

/** Menu order: what a founder with a broken app reads first. */
const ORDER = ['fix', 'wisdom', 'dispatch', 'drop'];

export const navPosts = () => {
  const posts = collect();
  const out = {};
  for (const stream of ORDER) {
    const mine = posts
      .filter((p) => p.stream === stream)
      .sort((a, b) => (a.date === b.date ? a.slug.localeCompare(b.slug) : a.date < b.date ? 1 : -1));
    out[stream] = {
      count: mine.length,
      href: `/${streamPath[stream]}`,
      latest: mine.slice(0, 3).map((p) => ({ title: p.title, href: pathOf(p), date: p.date })),
    };
  }
  return out;
};

export const navModule = () =>
  `/* Generated by scripts/generate-nav.mjs from the notes' frontmatter. Do not edit. */\n\nexport const NAV_POSTS = ${JSON.stringify(navPosts(), null, 2)} as const;\n`;
