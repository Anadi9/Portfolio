#!/usr/bin/env node
/**
 * Copies a kit release's manifest into the repo as `src/data/kit/releases/<version>.ts`.
 *
 *   node scripts/kit-add-release.mjs ~/Downloads/production-kit/release/dist/1.2.0
 *
 * A `.ts` module rather than the `.json` itself: the functions under `api/` run
 * as native ESM file by file (see serverless-imports.test.ts), and a JSON import
 * there needs import attributes that nothing in the build checks. The object is
 * the manifest verbatim; only the wrapper is added.
 *
 * Then add the import to `src/data/kit/index.ts` (newest first) and upload the
 * zips with `node scripts/kit-upload.mjs <same folder>`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/kit-add-release.mjs <release folder containing manifest.json>');
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(join(resolve(dir), 'manifest.json'), 'utf8'));
if (!/^\d+\.\d+\.\d+$/.test(manifest.version ?? '')) throw new Error(`bad version in manifest: ${manifest.version}`);

const out = join(import.meta.dirname, '..', 'src', 'data', 'kit', 'releases', `${manifest.version}.ts`);
writeFileSync(
  out,
  `// Generated by scripts/kit-add-release.mjs from the kit's release/dist/${manifest.version}/manifest.json. Don't edit by hand.\n` +
    `import type { Release } from '../types.js';\n\n` +
    `const release: Release = ${JSON.stringify(manifest, null, 2)};\n\nexport default release;\n`,
);
console.log(`wrote ${out}`);
console.log(`next: import it in src/data/kit/index.ts and run node scripts/kit-upload.mjs ${dir}`);
