// Copies docs/master-plan.md into src/data/plan.generated.ts so Coach and
// /admin can read the plan (serverless functions can't read docs/ at runtime).
// Runs in predev and prebuild; a test fails if the copy drifts.
import { readFileSync, writeFileSync } from 'node:fs';

const md = readFileSync('docs/master-plan.md', 'utf8');
const out = `/* Generated by scripts/generate-plan.mjs from docs/master-plan.md. Do not edit. */\nexport const MASTER_PLAN_MD = ${JSON.stringify(md)};\n`;
writeFileSync('src/data/plan.generated.ts', out);
console.log('[plan] src/data/plan.generated.ts');
